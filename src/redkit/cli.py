"""
redkit.cli — RedKit command-line entry point.

The **interactive TUI is the primary interface**. The headless mode
(``--no-tui``) is a minimal, frozen scripting surface: it runs one module
non-interactively and exits. New UX features land in the TUI; headless
flags are kept stable for scripts and CI.

Launch flags (``--target``, ``--module``, ``--resume``, ``--list-modules``,
``--version``, ``--config``) pre-populate the TUI. Utility flags
(``--init-config``, ``--help-options``) print information and exit.
"""

import argparse
import logging
import sys
from pathlib import Path
from typing import Any

from rich.console import Console
from rich.table import Table

from redkit import __version__
from redkit.core.config import load_config
from redkit.core.engine import Engine
from redkit.core.models import Finding
from redkit.core.session import Session
from redkit.core.tui import TUI, render_findings_table

logger = logging.getLogger(__name__)

#: Commented config.yaml template written by ``--init-config``.
CONFIG_TEMPLATE = """\
# RedKit Configuration
# Generated by `redkit --init-config` — every key is optional.

# --- Network defaults -------------------------------------------------------
default_threads: 10          # concurrent workers for thread-pooled modules
default_timeout: 5           # HTTP timeout in seconds
default_user_agent: "RedKit/{version} (Authorized Security Testing)"
verify_ssl: true             # validate TLS certificates (disable only for lab targets)
proxy: ""                    # e.g. "http://127.0.0.1:8080" to route through Burp/ZAP
rate_limit: 0.0              # minimum seconds between requests per host (0 = off)
max_retries: 0               # retries on connection errors per request (0 = off)
max_redirects: 10            # redirect hops followed per request
custom_headers: {{}}           # extra headers, e.g. {{ "Authorization": "Bearer ..." }}
custom_cookies: {{}}           # cookies for authenticated testing

# --- TUI behaviour ----------------------------------------------------------
ui_pause: true               # "Press Enter to continue" after each action
ui_clear_screen: false       # clear screen + banner between actions (kills scrollback)
live_feed: true              # echo findings to the console as they are discovered
ask_authorization: true      # confirm written permission before the first scan
save_history: true           # remember recent targets and last-used module options
history_file: ""             # override the default ~/.redkit/history.json

# --- Output -----------------------------------------------------------------
output_dir: "reports"        # report files are written here (relative to CWD)
max_findings_display: 50     # rows shown in the findings table

# --- Logging ----------------------------------------------------------------
log_file: "redkit.log"
log_level: "DEBUG"

# --- Misc -------------------------------------------------------------------
version: "{version}"
"""


def _setup_logging(config: dict, verbose: bool = False) -> None:
    """Configure logging: DEBUG output to the log file, optionally to stderr.

    Args:
        config: Merged RedKit configuration dict.
        verbose: When true, also mirror log output to stderr (keeps stdout
            clean for scripts).
    """
    log_file = Path(config.get("log_file", "redkit.log"))
    log_level = getattr(logging, str(config.get("log_level", "DEBUG")).upper(), logging.DEBUG)

    handlers: list[logging.Handler] = [logging.FileHandler(log_file, encoding="utf-8")]
    if verbose:
        stream = logging.StreamHandler(sys.stderr)
        stream.setLevel(logging.DEBUG)
        handlers.append(stream)

    logging.basicConfig(
        level=log_level,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        handlers=handlers,
    )
    logging.getLogger("urllib3").setLevel(logging.WARNING)
    logging.getLogger("requests").setLevel(logging.WARNING)


def _build_parser() -> argparse.ArgumentParser:
    """Build the RedKit argument parser.

    Returns:
        Configured argparse parser.
    """
    parser = argparse.ArgumentParser(
        prog="redkit",
        description="RedKit — Modular web red-teaming framework.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Examples:\n"
            "  redkit\n"
            "  redkit --target https://example.com --module 'XSS Tester'\n"
            "  redkit --module 'SQLi Tester' --help-options\n"
            "  redkit --target https://example.com --module 'SQLi Tester' \\\n"
            "         --opt param=id --no-tui\n"
            "  redkit --list-modules\n"
            "  redkit --resume redkit_session_example.com_20260101_120000.json\n"
            "  redkit --init-config\n"
        ),
    )
    parser.add_argument(
        "--target",
        "-t",
        metavar="URL",
        help="Pre-set the target URL and skip the Set Target prompt.",
    )
    parser.add_argument(
        "--module",
        "-m",
        metavar="NAME",
        help="Pre-select a module by name (exact or substring match).",
    )
    parser.add_argument(
        "--no-tui",
        action="store_true",
        help="Headless scripting mode: run the selected module and exit "
        "(requires --target and --module). Frozen surface — see docs.",
    )
    parser.add_argument(
        "--opt",
        metavar="KEY=VALUE",
        action="append",
        default=[],
        help="Set a module option (repeatable). Only valid with --no-tui.",
    )
    parser.add_argument(
        "--no-report",
        action="store_true",
        help="Headless mode: do not write JSON/HTML/Markdown reports after the run.",
    )
    parser.add_argument(
        "--save",
        metavar="PATH",
        type=Path,
        help="Headless mode: save the session to PATH after the run.",
    )
    parser.add_argument(
        "--resume",
        metavar="PATH",
        type=Path,
        help="Resume a previously saved session file.",
    )
    parser.add_argument(
        "--last",
        action="store_true",
        help="Resume the most recent session file in the current directory.",
    )
    parser.add_argument(
        "--help-options",
        action="store_true",
        help="Print the option table for --module NAME and exit.",
    )
    parser.add_argument(
        "--init-config",
        action="store_true",
        help="Write a commented config.yaml to the current directory and exit.",
    )
    parser.add_argument(
        "--config",
        "-c",
        metavar="PATH",
        type=Path,
        help="Path to an alternative config.yaml file.",
    )
    parser.add_argument(
        "--list-modules",
        action="store_true",
        help="List all discovered modules and exit.",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Mirror log output to stderr (stdout stays clean for scripts).",
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"RedKit {__version__}",
    )
    return parser


def _resolve_module(engine: Engine, name: str) -> tuple[Any, str | None]:
    """Resolve a module by exact or substring name match.

    Args:
        engine: Discovered Engine instance.
        name: Module display name, exact (case-insensitive) or a substring.

    Returns:
        Tuple of (module, None) on success or (None, error_message) on
        failure. The error message lists candidates or available modules.
    """
    module = engine.get_module_by_name(name)
    if module is not None:
        return module, None

    needle = name.lower()
    candidates = [m for m in engine.get_all_modules() if needle in m.name.lower()]
    if len(candidates) == 1:
        return candidates[0], None
    if len(candidates) > 1:
        listing = ", ".join(m.name for m in candidates)
        return None, f"Ambiguous module '{name}' — matches: {listing}"
    available = ", ".join(m.name for m in engine.get_all_modules())
    return None, f"Module '{name}' not found. Available modules: {available}"


def _print_module_list(engine: Engine) -> None:
    """Print all discovered modules grouped by category.

    Args:
        engine: Discovered Engine instance.
    """
    console = Console()
    table = Table(title=f"RedKit {__version__} — Modules", box=None)
    table.add_column("Category", style="bold yellow")
    table.add_column("Module", style="bold cyan", min_width=25)
    table.add_column("Description", style="white")
    table.add_column("Author", style="dim")

    for category, mods in engine.get_modules_by_category().items():
        for mod in mods:
            table.add_row(category, mod.name, mod.description, mod.author)
    console.print(table)


def _print_module_options(engine: Engine, name: str) -> int:
    """Print a module's options table (for --help-options).

    Args:
        engine: Discovered Engine instance.
        name: Module name (exact or substring).

    Returns:
        Process exit code (0 success, 1 failure).
    """
    module, error = _resolve_module(engine, name)
    console = Console()
    if error:
        console.print(f"[bold red]✖ {error}[/bold red]")
        return 1
    table = Table(title=f"{module.name} — Options", box=None)
    table.add_column("Option", style="bold yellow")
    table.add_column("Type", style="dim")
    table.add_column("Required", style="white")
    table.add_column("Default", style="cyan")
    table.add_column("Description", style="white")
    for key, meta in module.options.items():
        declared = meta.get("type")
        table.add_row(
            key,
            declared.__name__ if declared else "str",
            "Yes" if meta.get("required") else "No",
            "—" if meta.get("value") is None else str(meta.get("value")),
            meta.get("description", ""),
        )
    console.print(table)
    return 0


def _init_config() -> int:
    """Write a commented config.yaml to the current directory.

    Returns:
        Process exit code (0 success, 1 when the file already exists).
    """
    target = Path.cwd() / "config.yaml"
    if target.exists():
        print(f"[Error] {target} already exists — refusing to overwrite.")
        return 1
    target.write_text(CONFIG_TEMPLATE.format(version=__version__), encoding="utf-8")
    print(f"[OK] Wrote {target}")
    return 0


def _find_last_session() -> Path | None:
    """Return the most recently modified session file in the current directory.

    Returns:
        Path to the newest ``redkit_session*.json``, or None when there is
        no session file.
    """
    candidates = sorted(Path.cwd().glob("redkit_session*.json"), key=lambda p: p.stat().st_mtime)
    return candidates[-1] if candidates else None


def _run_headless(
    args: argparse.Namespace,
    config: dict,
    session: Session,
    engine: Engine,
) -> int:
    """Run a single module non-interactively and print its findings.

    This is the frozen scripting surface: behaviour is kept stable so
    scripts and CI can rely on it.

    Args:
        args: Parsed CLI arguments.
        config: Merged RedKit configuration dict.
        session: Active Session instance (target already applied).
        engine: Discovered Engine instance.

    Returns:
        Process exit code (0 on success, 1 on any error, 130 on interrupt).
    """
    console = Console()

    if not args.target or not args.module:
        console.print("[bold red]✖ --no-tui requires both --target and --module.[/bold red]")
        return 1

    module, error = _resolve_module(engine, args.module)
    if error:
        console.print(f"[bold red]✖ {error}[/bold red]")
        return 1

    session.set_active_module(module)
    if "target" in module.options:
        module.set_option("target", session.target)

    for pair in args.opt:
        key, sep, value = pair.partition("=")
        if not sep:
            console.print(f"[bold red]✖ Invalid --opt '{pair}' — expected KEY=VALUE.[/bold red]")
            return 1
        try:
            module.set_option(key, value)
        except (KeyError, ValueError) as exc:
            console.print(f"[bold red]✖ {exc}[/bold red]")
            return 1

    try:
        module.validate_options()
    except ValueError as exc:
        console.print(f"[bold red]✖ {exc}[/bold red]")
        return 1

    console.print(f"[bold]Running {module.name}[/bold] on {session.target}\n")
    try:
        module.run()
    except KeyboardInterrupt:
        console.print("\n[bold red]Interrupted.[/bold red]")
        return 130
    except Exception as exc:  # noqa: BLE001
        console.print(f"[bold red]✖ Module error: {exc}[/bold red]")
        logger.error("Module '%s' raised an exception: %s", module.name, exc, exc_info=True)
        return 1

    findings: list[Finding] = module.get_findings()
    session.add_findings(module.name, findings)

    console.print(f"\n[bold green]✔ Scan complete.[/bold green] {len(findings)} finding(s) recorded.\n")
    if findings:
        render_findings_table(console, findings)

    if args.save:
        try:
            saved = session.save(args.save)
            console.print(f"[bold green]✔ Session saved:[/bold green] {saved}")
        except (OSError, ValueError) as exc:
            console.print(f"[bold red]✖ Session save failed: {exc}[/bold red]")
            return 1

    if not args.no_report and findings:
        try:
            from redkit.core.report import Reporter

            reporter = Reporter(session.export_session(), output_dir=config.get("output_dir", "reports"))
            json_path, html_path, md_path = reporter.generate()
            console.print(f"[bold green]✔ JSON:[/bold green] {json_path}")
            console.print(f"[bold green]✔ HTML:[/bold green] {html_path}")
            console.print(f"[bold green]✔ Markdown:[/bold green] {md_path}")
        except Exception as exc:  # noqa: BLE001
            console.print(f"[bold red]✖ Report generation failed: {exc}[/bold red]")
            logger.error("Report generation error: %s", exc, exc_info=True)
            return 1

    return 0


def main(argv: list[str] | None = None) -> int:
    """Bootstrap RedKit and launch the interactive or headless flow.

    Args:
        argv: Command-line arguments (defaults to sys.argv[1:]). Exposed for
            testability.

    Returns:
        Process exit code.
    """
    parser = _build_parser()
    args = parser.parse_args(argv)

    config = load_config(args.config)
    _setup_logging(config, verbose=args.verbose)
    logger.info("RedKit %s starting up.", __version__)

    # Informational flags that only need the config -----------------------
    if args.init_config:
        return _init_config()

    session = Session()
    if args.resume:
        try:
            session = Session.load(args.resume)
        except ValueError as exc:
            print(f"[Error] {exc}")
            return 1
    elif args.last:
        last = _find_last_session()
        if last is None:
            print("[Error] No redkit_session*.json files in the current directory.")
            return 1
        try:
            session = Session.load(last)
        except ValueError as exc:
            print(f"[Error] {exc}")
            return 1

    engine = Engine(config=config)
    engine.discover()

    if args.list_modules:
        _print_module_list(engine)
        return 0

    if args.help_options:
        if not args.module:
            print("[Error] --help-options requires --module NAME.")
            return 1
        return _print_module_options(engine, args.module)

    # Apply CLI pre-population
    if args.target:
        try:
            session.set_target(args.target)
            logger.info("CLI target pre-set: %s", args.target)
        except ValueError as exc:
            print(f"[Error] Invalid target: {exc}")
            return 1

    if args.module:
        module, error = _resolve_module(engine, args.module)
        if error:
            print(f"[Error] {error}")
            return 1
        session.set_active_module(module)
        # Pre-fill target option if module has one
        if "target" in module.options and session.target:
            module.set_option("target", session.target)
        logger.info("CLI module pre-set: %s", args.module)

    if args.no_tui:
        return _run_headless(args, config, session, engine)

    # Launch TUI
    tui = TUI(session=session, engine=engine, config=config)
    try:
        tui.run()
    except KeyboardInterrupt:
        print("\n\n[bold red]Exiting RedKit…[/bold red] Stay safe and hack ethically.")
        logger.info("RedKit terminated by user (KeyboardInterrupt).")
        return 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
